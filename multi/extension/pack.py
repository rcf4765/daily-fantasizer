#!/usr/bin/env python3
"""Zip the extension for the site's /extension.zip download, with SITE_URL from multi/worker/wrangler.toml put into
config.js. Writes multi/worker/src/extension_zip.js. Run before each `npx wrangler deploy` (npm run deploy does it)."""
import base64, io, pathlib, re, zipfile
HERE = pathlib.Path(__file__).resolve().parent
toml = (HERE.parent / 'worker' / 'wrangler.toml').read_text()
site = re.search(r'^SITE_URL\s*=\s*"([^"]+)"', toml, re.M).group(1).rstrip('/')
buf = io.BytesIO()
with zipfile.ZipFile(buf, 'w', zipfile.ZIP_DEFLATED) as z:
    for f in sorted(HERE.iterdir()):
        if f.name in ('pack.py', 'README.md') or f.is_dir():
            continue
        data = f.read_bytes()
        if f.name == 'config.js':
            data = re.sub(rb"'https://fantasizer\.YOUR-SUBDOMAIN\.workers\.dev'", f"'{site}'".encode(), data)
        z.writestr(f'daily-fantasizer-espn/{f.name}', data)
out = HERE.parent / 'worker' / 'src' / 'extension_zip.js'
out.write_text('// Generated by multi/extension/pack.py: the Chrome extension zip served at /extension.zip.\n'
               f'export const EXTENSION_ZIP = "{base64.b64encode(buf.getvalue()).decode()}";\n')
print(f'{out} ({len(buf.getvalue())} bytes, site {site})')
